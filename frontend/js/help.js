function openYiReadHelp(){
  const existing=document.querySelector('.yiread-help');if(existing?.open)return;
  const dialog=el('dialog','yiread-help');dialog.setAttribute('aria-labelledby','yiread-help-title');
  const heading=el('div','dialog-heading');const title=el('h2','','YiRead 使用帮助');title.id='yiread-help-title';
  const close=el('button','quiet','关闭');close.type='button';close.onclick=()=>dialog.close();heading.append(title,close);
  const intro=el('p','settings-note','译·读 · 合一文献阅读翻译助手。按主题查看完整用法，打开帮助不会调用翻译接口。');
  const nav=el('nav','help-topics');nav.setAttribute('aria-label','帮助主题');const body=el('div','help-content');
  for(const [name,paragraphs] of yiReadGuide){
    const section=el('section','help-section');section.append(el('h3','',name));
    for(const paragraph of paragraphs)section.append(el('p','',paragraph));body.append(section);
    const button=el('button','quiet',name);button.type='button';button.onclick=()=>section.scrollIntoView({block:'start'});nav.append(button);
  }
  dialog.append(heading,intro,nav,body);dialog.addEventListener('close',()=>dialog.remove());document.body.append(dialog);dialog.showModal();
}
document.querySelectorAll('[data-help]').forEach(button=>button.addEventListener('click',openYiReadHelp));
